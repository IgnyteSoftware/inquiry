using Inquiry.Generators.Infrastructure;
using Inquiry.Generators.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Immutable;
using System.Text;

namespace Inquiry.Generators;

/// <summary>
/// Emits the DI registration class consumed by <c>AddInquiry()</c> via reflection.
/// </summary>
internal static class RegistrationEmitter
{
    public static void Emit(
        SourceProductionContext context,
        ImmutableArray<EntityRegistrationModel> entityRegistrations,
        ImmutableArray<StoreRegistrationModel> storeRegistrations)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("namespace Inquiry.Generated");
        source.AppendLine("{");
        source.AppendLine("    internal sealed class InquiryGeneratedServiceRegistration : global::Inquiry.DependencyInjection.IInquiryServiceRegistration");
        source.AppendLine("    {");
        source.AppendLine("        public void AddServices(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        source.AppendLine("        {");
        source.AppendLine("            if (services is null)");
        source.AppendLine("            {");
        source.AppendLine("                throw new global::System.ArgumentNullException(nameof(services));");
        source.AppendLine("            }");
        source.AppendLine();

        foreach (var registration in entityRegistrations)
        {
            var entityType = registration.EntityType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var materializerType = GeneratorHelpers.GetGeneratedTypeName(registration.EntityType, registration.MaterializerTypeName);
            source.AppendLine($"            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddSingleton<global::Inquiry.Materialization.IInquiryEntityMaterializer<{entityType}>, {materializerType}>(services);");
        }

        foreach (var registration in storeRegistrations)
        {
            var storeType = registration.StoreType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var generatedType = GeneratorHelpers.GetGeneratedTypeName(registration.StoreType, registration.GeneratedTypeName);
            source.AppendLine($"            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddTransient<{storeType}, {generatedType}>(services);");
        }

        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");

        context.AddSource("InquiryGeneratedServiceRegistration.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }
}
