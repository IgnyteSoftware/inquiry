using Fulfillment;
using Inquiry.Stores;

namespace Inquiry.FeatureCatalog.Locking;

/// <summary>
/// Test-side declarations for the row-locking guide. The guide publishes <see cref="WorkItemStore"/>
/// and <see cref="WorkItemService"/> verbatim; these extra methods seed rows and probe the lock modes the
/// guide documents only in its provider matrix.
/// </summary>
public partial class WorkItemProbeStore : InquiryStore<WorkItem>
{
    [InquiryInsert]
    public partial Task<WorkItem?> InsertReturningAsync(WorkItem item, CancellationToken cancellationToken = default);

    [InquirySelectOneByKey]
    public partial Task<WorkItem?> GetAsync(long id, CancellationToken cancellationToken = default);

    [InquirySelectOneByKey(LockMode = InquiryLockMode.UpdateNoWait)]
    public partial Task<WorkItem?> GetForUpdateNoWaitAsync(long id, CancellationToken cancellationToken = default);
}

/// <summary>Per-dialect DDL for the <see cref="WorkItem"/> table used by the row-locking scenarios.</summary>
public static class LockingSchema
{
    public const string PostgreSqlDdl = """
        CREATE TABLE "WorkItem" ("Id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "QueueId" INTEGER NOT NULL, "State" INTEGER NOT NULL, "Attempts" INTEGER NOT NULL);
        CREATE INDEX "IX_WorkItem_Queue" ON "WorkItem" ("QueueId", "State");
        """;

    public const string SqlServerDdl = """
        CREATE TABLE WorkItem (Id BIGINT IDENTITY(1,1) PRIMARY KEY, QueueId INT NOT NULL, State INT NOT NULL, Attempts INT NOT NULL);
        CREATE INDEX IX_WorkItem_Queue ON WorkItem (QueueId, State);
        """;

    public const string MySqlDdl = """
        CREATE TABLE WorkItem (Id BIGINT AUTO_INCREMENT PRIMARY KEY, QueueId INT NOT NULL, State INT NOT NULL, Attempts INT NOT NULL, INDEX IX_WorkItem_Queue (QueueId, State));
        """;

    public const string OracleDdl = """
        CREATE TABLE WorkItem (Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, QueueId NUMBER(10) NOT NULL, State NUMBER(10) NOT NULL, Attempts NUMBER(10) NOT NULL);
        CREATE INDEX IX_WorkItem_Queue ON WorkItem (QueueId, State);
        """;
}
