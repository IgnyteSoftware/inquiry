        Assert.Equal(0L, await VisibleCountAsync(tx));
    }

    [SkippableFact]
    public async Task TheValueIsBoundAsAParameterNotInterpolated()
    {
        Skip.IfNot(_fixture.IsAvailable, _fixture.SkipReason);
        var (harness, services) = await CreateAsync();
        await using var _ = harness;
        await using var provider = services;
        var inquiry = provider.GetRequiredService<IInquiry>();

        await using var tx = await inquiry.BeginTransactionAsync();

        // A value carrying SQL syntax is data, not code: it round-trips verbatim and the table
        // referenced in the injection attempt is untouched.
        const string hostile = "t1'; DROP TABLE rls_doc; --";
        await tx.SetLocalAsync(TenantSetting, hostile);

        Assert.Equal(hostile, await CurrentSettingAsync(tx));
        Assert.Equal(0L, await VisibleCountAsync(tx));
    }
}
